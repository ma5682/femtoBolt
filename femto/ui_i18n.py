def preference_path() -> Path:
    base = Path(os.environ.get("LOCALAPPDATA", str(Path.home()))) / "FemtoSceneDemo"
    return base / "ui_preferences.json"


def load_language(default: str = "zh") -> str:
    fallback = default if default in SUPPORTED_LANGUAGES else "zh"
    try:
        payload = json.loads(preference_path().read_text(encoding="utf-8"))
        language = str(payload.get("language", fallback))
    except (OSError, ValueError, TypeError):
        return fallback
    return language if language in SUPPORTED_LANGUAGES else fallback


def save_language(language: str) -> None:
    if language not in SUPPORTED_LANGUAGES:
        raise ValueError(f"Unsupported UI language: {language}")
    path = preference_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(".tmp")
    temporary.write_text(
        json.dumps({"language": language}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    temporary.replace(path)


def tr(language: str, key: str, **values: Any) -> str:
    lang = language if language in SUPPORTED_LANGUAGES else "zh"
    template = STRINGS.get(lang, {}).get(key) or STRINGS["zh"].get(key) or key
    return template.format(**values) if values else template


def localized_mapping(language: str, prefix: str, keys: tuple[str, ...]) -> dict[str, str]:
    return {key: tr(language, f"{prefix}.{key}") for key in keys}
