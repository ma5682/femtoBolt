"""Bounded candidate ranking for research-only scan-edge fractional seeds.

Floating-point proximity is used only to select work. It is not a coverage
proof, a surface distance, or an acceptance check. Callers must independently
validate the old proof, target and current route, then reprove all results.
"""
from __future__ import annotations

import math
import numpy as np

from femto.geometry.exact_surface import _dyadic_coefficients
from femto.planning import coverage_certificate as coverage, scan_fraction_seeds
from femto.planning.surface_trajectory import ScanSegment

VERSION = 'research-pending-leaf-fraction-priority-v1'
MAX_PENDING = 5000
MAX_EDGES = 50_000
MAX_EDGE_VISITS = 200_000
MAX_COMPARISONS = 10_000_000
MAX_BATCHES = 8
MAX_BATCHED_PENDING = 20_000
MAX_BATCHED_COMPARISONS = 40_000_000


def propose(trajectory, target, previous_certificate, pending_leaves, *,
            nearest_edges_per_leaf=2, radius_m=.003, denominator=8, check=lambda:None):
    """Rank source-edge requests near confirmed old leaves; never infer coverage.

    ``target`` must be the independently validated old target asset and
    ``pending_leaves`` must refer to its replayed previous certificate. The
    current trajectory must separately pass the original whole-edge checks.
    All returned coordinates and upward rounding bounds are regenerated by
    ``scan_fraction_seeds``; subsequent proof replay remains mandatory.
    """
    check()
    coverage._checked_assets(previous_certificate, check)
    if (not isinstance(pending_leaves, (list, tuple, np.ndarray))
            or len(pending_leaves)>MAX_PENDING
            or type(nearest_edges_per_leaf) is not int or not 1<=nearest_edges_per_leaf<=3
            or isinstance(radius_m, bool) or not isinstance(radius_m, (float, int))
            or not math.isfinite(radius_m) or not 0<radius_m<=1
            or type(denominator) is not int or not 2<=denominator<=scan_fraction_seeds.MAX_DENOMINATOR
            or denominator & (denominator-1)):
        raise ValueError('分数位置优先级参数无效或超过预算')
    indices=[]
    for value in pending_leaves:
        if isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, np.integer)):
            raise ValueError('待确认旧单元索引无效')
        indices.append(int(value))
    if len(set(indices))!=len(indices):raise ValueError('待确认旧单元索引重复')
    indices.sort()
    previous=previous_certificate.arrays
    if any(i<0 or i>=len(previous['root']) or previous['status'][i]!=1 for i in indices):
        raise ValueError('待确认旧单元必须来自原已确认分区')
    arrays=getattr(target,'arrays',None)
    if not isinstance(arrays,dict):raise ValueError('原目标数组缺失')
    try:
        vertices=np.asarray(arrays['vertices']);faces=np.asarray(arrays['faces'])
        source_faces=np.asarray(arrays['source_face']);barycentric=np.asarray(arrays['barycentric'])
        region_faces=np.asarray(arrays['region_faces'])
    except KeyError as error:raise ValueError('原目标数组缺失') from error
    if (vertices.ndim!=2 or vertices.shape[1:]!=(3,) or faces.ndim!=2 or faces.shape[1:]!=(3,)
            or faces.dtype.kind not in 'iu' or source_faces.ndim!=1 or source_faces.dtype.kind not in 'iu'
            or barycentric.shape!=(len(source_faces),3,3) or region_faces.ndim!=1 or region_faces.dtype.kind not in 'iu'
            or not np.isfinite(vertices).all() or not np.isfinite(barycentric).all()
            or (faces.size and (faces.min()<0 or faces.max()>=len(vertices)))
            or (source_faces.size and (source_faces.min()<0 or source_faces.max()>=len(faces)))):
        raise ValueError('原目标几何形状或索引无效')
    roots=previous['root'][indices]
    if len(roots) and (roots.min()<0 or roots.max()>=len(source_faces)):
        raise ValueError('旧证据与原目标单元不匹配')
    edges=[];segment_ids=set();examined=0
    for item in trajectory.ordered_items:
        if not isinstance(item,ScanSegment):continue
        if type(item.segment_index) is not int or item.segment_index in segment_ids:
            raise ValueError('扫描段索引无效或重复')
        segment_ids.add(item.segment_index)
        for edge,(a,b) in enumerate(zip(item.points,item.points[1:])):
            examined+=1
            if examined%256==0:check()
            if examined>MAX_EDGE_VISITS:raise ValueError('分数位置路线段遍历超过预算')
            role=b.get('role')
            if role not in (None,'scan','connector'):raise ValueError('扫描边角色无效')
            if role=='connector' or a['xyz_m']==b['xyz_m']:continue
            left,right=np.asarray(a['xyz_m'],float),np.asarray(b['xyz_m'],float)
            if left.shape!=(3,) or right.shape!=(3,) or not np.isfinite([left,right]).all():
                raise ValueError('扫描边坐标无效')
            edges.append((item.segment_index,edge,left,right))
            if len(edges)>MAX_EDGES:raise ValueError('分数位置扫描边超过预算')
    if len(indices)*len(edges)>MAX_COMPARISONS:raise ValueError('分数位置距离筛选超过预算')
    if not indices or not edges:
        return [], [], dict(version=VERSION,pending_leaves=len(indices),scan_edges=len(edges),
            selected_requests=0,proposed_records=0,leaves_with_near_candidate=0,
            semantics='priority_only_not_coverage_or_physical_motion')
    A=np.asarray([e[2] for e in edges]);B=np.asarray([e[3] for e in edges]);direction=B-A
    length2=np.einsum('ij,ij->i',direction,direction)
    if not np.isfinite(length2).all() or np.any(length2<=0):raise ValueError('扫描边长度无效')
    source=vertices[faces[source_faces[roots]]]
    root_xyz=np.einsum('nij,njk->nik',barycentric[roots],source)
    depth=previous['depth'][indices];code=previous['code'][indices]
    keys=np.left_shift(depth.astype('u8'),32)|code.astype('u8')
    unique,inverse=np.unique(keys,return_inverse=True)
    coeff=np.asarray([_dyadic_coefficients(int(k)>>32,int(k)&0xffffffff) for k in unique])[inverse]
    centers=np.einsum('nij,njk->nik',coeff,root_xyz).mean(axis=1)
    if not np.isfinite(centers).all():raise ValueError('原目标候选中心无效')
    hits=set();near=0
    for i,center in enumerate(centers):
        if i%32==0:check()
        projection=np.clip(np.einsum('ij,ij->i',center-A,direction)/length2,0.,1.)
        if not np.isfinite(projection).all():raise ValueError('分数位置投影无效')
        numerators=np.clip(np.rint(projection*denominator).astype(int),1,denominator-1)
        points=A+direction*(numerators/denominator)[:,None]
        distances=np.linalg.norm(points-center,axis=1)
        if not np.isfinite(distances).all():raise ValueError('分数位置距离无效')
        valid=np.flatnonzero(distances<=radius_m)
        if len(valid):near+=1
        order=valid[np.argsort(distances[valid],kind='stable')]
        for index in order[:nearest_edges_per_leaf]:hits.add((int(index),int(numerators[index])))
    requests=[(edges[index][0],edges[index][1],numerator,denominator) for index,numerator in sorted(hits)]
    positions,_=scan_fraction_seeds.propose(trajectory,region_faces,requests,check=check)
    check()
    return requests,positions,dict(version=VERSION,pending_leaves=len(indices),scan_edges=len(edges),
        selected_requests=len(requests),proposed_records=len(positions),leaves_with_near_candidate=near,
        semantics='priority_only_not_coverage_or_physical_motion')


def propose_batched(trajectory,target,previous_certificate,pending_leaves,*,
                    nearest_edges_per_leaf=2,radius_m=.003,denominator=8,check=lambda:None):
    """Rank every pending leaf in bounded batches, without asserting coverage.

    Small inputs keep the original path and ordering. Larger inputs are fully
    processed or rejected: no pending leaf is silently dropped. Returned
    positions are rederived from the deduplicated combined request list.
    """
    if not isinstance(pending_leaves,(list,tuple,np.ndarray)):
        raise ValueError('待确认旧单元索引无效')
    if len(pending_leaves)<=MAX_PENDING:
        try:
            return propose(trajectory,target,previous_certificate,pending_leaves,
                nearest_edges_per_leaf=nearest_edges_per_leaf,radius_m=radius_m,denominator=denominator,check=check)
        except ValueError as error:
            if str(error)!='分数位置距离筛选超过预算':raise
    check();coverage._checked_assets(previous_certificate,check)
    if len(pending_leaves)>MAX_BATCHED_PENDING:raise ValueError('分数位置分批待确认单元超过预算')
    indices=[]
    for value in pending_leaves:
        if isinstance(value,(bool,np.bool_)) or not isinstance(value,(int,np.integer)):
            raise ValueError('待确认旧单元索引无效')
        indices.append(int(value))
    if len(set(indices))!=len(indices):raise ValueError('待确认旧单元索引重复')
    indices.sort();edges=0;examined=0;segment_ids=set()
    for item in trajectory.ordered_items:
        if not isinstance(item,ScanSegment):continue
        if type(item.segment_index) is not int or item.segment_index in segment_ids:
            raise ValueError('扫描段索引无效或重复')
        segment_ids.add(item.segment_index)
        for a,b in zip(item.points,item.points[1:]):
            examined+=1
            if examined%256==0:check()
            if examined>MAX_EDGE_VISITS:raise ValueError('分数位置路线段遍历超过预算')
            role=b.get('role')
            if role not in (None,'scan','connector'):raise ValueError('扫描边角色无效')
            if role!='connector' and a['xyz_m']!=b['xyz_m']:
                edges+=1
                if edges>MAX_EDGES:raise ValueError('分数位置扫描边超过预算')
    if len(indices)*edges>MAX_BATCHED_COMPARISONS:raise ValueError('分数位置分批距离筛选超过预算')
    per_batch=min(MAX_PENDING,MAX_COMPARISONS//max(1,edges))
    if per_batch<1 or math.ceil(len(indices)/per_batch)>MAX_BATCHES:
        raise ValueError('分数位置分批次数超过预算')
    requests=set();near=0;batches=0
    for offset in range(0,len(indices),per_batch):
        check();part,_,report=propose(trajectory,target,previous_certificate,indices[offset:offset+per_batch],
            nearest_edges_per_leaf=nearest_edges_per_leaf,radius_m=radius_m,denominator=denominator,check=check)
        requests.update(part);near+=report['leaves_with_near_candidate'];batches+=1
        if len(requests)>scan_fraction_seeds.MAX_REQUESTS:raise ValueError('分数位置分批请求超过预算')
    ordered=sorted(requests)
    positions,_=scan_fraction_seeds.propose(trajectory,target.arrays['region_faces'],ordered,check=check)
    check();return ordered,positions,dict(version='research-batched-fraction-priority-v1',pending_leaves=len(indices),
        processed_leaves=len(indices),scan_edges=edges,batches=batches,selected_requests=len(ordered),
        proposed_records=len(positions),leaves_with_near_candidate=near,
        semantics='priority_only_not_coverage_or_physical_motion')
